import { ExecutionContext, Injectable } from '@nestjs/common';
import { Reflector } from '@nestjs/core';
import { AuthGuard } from '@nestjs/passport';
import { IS_PUBLIC_KEY } from '../../../common/decorators/public.decorator';

/**
 * Authenticates portal routes with the portal JWT strategy. Applied at the
 * controller level. Public portal routes (login, refresh, invite/reset consume)
 * are marked @Public() and bypass authentication.
 */
@Injectable()
export class PortalAuthGuard extends AuthGuard('jwt-portal') {
  constructor(private reflector: Reflector) {
    super();
  }

  canActivate(context: ExecutionContext) {
    const isPublic = this.reflector.getAllAndOverride<boolean>(IS_PUBLIC_KEY, [
      context.getHandler(),
      context.getClass(),
    ]);
    if (isPublic) return true;
    return super.canActivate(context);
  }
}
